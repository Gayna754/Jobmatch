"""Create a blind yes/no audit of 30 match explanations."""
from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core import grounded_reason, grounded_reasons, get_jobs
from app.llm import llm_enabled

ROOT = Path(__file__).parent


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--use-llm", action="store_true", help="Use the configured provider; may incur API usage.")
    args = parser.parse_args()
    if args.use_llm and not llm_enabled():
        raise SystemExit("No configured LLM provider key. Omit --use-llm to audit local grounded explanations.")
    profiles = json.loads((ROOT / "benchmark_profiles.json").read_text(encoding="utf-8"))
    manifest = json.loads((ROOT / "blind_pool_manifest.json").read_text(encoding="utf-8"))
    jobs = {job["id"]: job for job in get_jobs()}
    profile_by_id = {item["id"]: item for item in profiles}
    candidates = []
    for item in profiles:
        if item["split"] != "test":
            continue
        for posting_id in manifest["systems"][item["id"]]["hybrid_filtered"]:
            if posting_id in jobs:
                candidates.append((item, jobs[posting_id]))
    candidates = list({(item["id"], job["id"]): (item, job) for item, job in candidates}.values())
    random.Random(3182).shuffle(candidates)
    candidates = candidates[:30]
    if len(candidates) < 30:
        raise SystemExit(f"Only {len(candidates)} distinct test explanations available; need 30.")

    rows = []
    for item in profiles:
        group = [(profile, job) for profile, job in candidates if profile["id"] == item["id"]]
        if not group:
            continue
        generated = (grounded_reasons(item["profile"], [job for _, job in group]) if args.use_llm
                     else [grounded_reason(item["profile"], job) for _, job in group])
        for (profile, job), reason in zip(group, generated):
            rows.append({"profile_id": profile["id"], "posting_id": job["id"],
                         "title": job.get("title", ""), "company": job.get("company", ""),
                         "url": job.get("url", ""), "reason": reason, "faithful": ""})
    random.Random(9035).shuffle(rows)
    path = ROOT / "explanation_audit.csv"
    with path.open("w", newline="", encoding="utf-8-sig") as stream:
        writer = csv.DictWriter(stream, fieldnames=("profile_id", "posting_id", "title", "company", "url", "reason", "faithful"))
        writer.writeheader()
        writer.writerows(rows)
    method = "configured LLM" if args.use_llm else "local source-grounded fallback"
    print(f"Wrote {len(rows)} shuffled explanations generated by {method} to {path}.")
    print("Compare every claim with the linked posting; enter yes/no in faithful. Do not open the system manifest while auditing.")


if __name__ == "__main__":
    main()
